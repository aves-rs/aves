/// Reusable runtime supervisor for an installed set of domains.
pub struct Runtime<RootBroadcast>
where
    RootBroadcast: Clone + Send + 'static,
{
    /// Installed domain descriptors.
    domains: Vec<DomainDescriptor<EventBus<RootBroadcast>>>,

    /// Registry for service slots used by the runtime.
    services: ServiceSlotRegistry,

    /// Handle to the runtime's bus.
    bus: BusHandle<RootBroadcast>,

    /// Handle to the auth service.
    auth_service: Arc<dyn AuthSudoService>,

    /// Task that handles auth admission.
    auth_task: JoinHandle<()>,

    /// Registry for auth admission.
    auth_admission_registry: AuthAdmissionRegistry,

    /// Handle to the pairing coordinator.
    pairing_owner: PairingOwner,

    /// Handle to the running Iroh substrate.
    iroh: RunningIrohSubstrate,

    /// Flag indicating whether shutdown has been started.
    shutdown_started: AtomicBool,
}

impl<RootBroadcast> Runtime<RootBroadcast>
where
    RootBroadcast: Clone + Send + 'static,
{
    /// Creates a runtime from opaque construction inputs and installed domains.
    pub async fn new(
        options: RuntimeOptions,
        domains: Vec<DomainDescriptor<EventBus<RootBroadcast>>>,
    ) -> Result<Self, BusControlError> {
        let RuntimeOptions {
            keyring_service_namespace,
            mut construction_inputs,
            transport_bindings,
            data_root,
            remote_operation_installer,
        } = options;
        if keyring_service_namespace.is_empty() {
            return Err(BusControlError::EmptyKeyringServiceNamespace);
        }

        // first we constrcut the bus and the core services registry
        let mut bus = EventBus::new();
        let mut services = ServiceSlotRegistry::new();
        let bus_publisher = services.publisher::<dyn BusSudoService>();

        // next we construct the auth domain and its handoff
        let mut auth_construction = None;
        let auth_options = AuthBootOptions {
            namespace: keyring_service_namespace,
            audience: Uuid::new_v4(),
            peer_config_path: data_root.join("auth").join("peers.json"),
        };
        let auth_domain = DomainDescriptor::for_domain::<AuthDomain>("auth");
        {
            let mut facade = ConstructionFacade::new_with_auth(
                &mut bus,
                &mut services,
                &*construction_inputs,
                &auth_options,
                &mut auth_construction,
            );
            auth_domain.construct(&mut facade).await;
        }

        // The Auth actor supplies the machine key only; public admission is installed
        // after the native substrate and bilateral pairing coordinator exist.
        let auth_construction = auth_construction
            .expect("built-in Auth construction must provide its handoff")
            .map_err(BusControlError::from)?;
        let auth_task = auth_construction.actor_task;
        let registry = auth_construction.admission_registry.clone();
        let peer_connectivity = PeerConnectivity::new(false);
        let substrate = IrohSubstrate::prepare(
            &data_root.join("flows"),
            &auth_construction.machine_secret_key,
            peer_connectivity.clone(),
        )
        .await
        .map_err(|error| BusControlError::Serve {
            protocol: "iroh",
            source: Box::new(error),
        })?;

        let mobility_service: Arc<dyn FlowMobilityService> = Arc::new(RuntimeFlowMobilityService {
            services: substrate.flow_services(),
            pairing_owner: auth_construction.pairing_owner.clone(),
            auth_service: auth_construction.service.clone(),
            source_issuer: auth_construction.machine_secret_key.public().into(),
        });

        if let Some(construction_inputs) = construction_inputs.downcast_mut::<ConstructionInputs>() {
            construction_inputs.insert(substrate.flow_services());
            construction_inputs.insert(mobility_service);
            construction_inputs.insert(peer_connectivity.clone());
        }
        let auth_verifier = auth_construction.service.clone();
        let auth_service = auth_construction.service.clone();

        // once we have auth configured, add it to the buss
        bus.install_auth(AuthAdmissionConfiguration {
            registry: registry.clone(),
            verifier: auth_verifier,
            audience: auth_options.audience,
        });

        // now install the root jwt and context
        let root_jwt = auth_construction.root_jwt;
        let root_context = BusRpcContext::authenticated(bus.input_sender(), root_jwt.clone());

        // once we have the bus and it's auth then we install the normal domains
        let mut installed_domains = Vec::with_capacity(domains.len() + 1);
        installed_domains.push(auth_domain);
        installed_domains.extend(domains);

        // Construction is intentionally sequential: every callback receives
        // the same mutable registration borrow, and a construction panic is
        // fatal without Aves rollback or compensation. The facade contains
        // only the marker-declared typed slots; reads remain late-bound.
        for domain in installed_domains.iter().skip(1) {
            let mut facade = ConstructionFacade::new_with_root_context(
                &mut bus,
                &mut services,
                &*construction_inputs,
                root_context.clone(),
            );
            domain.construct(&mut facade).await;
        }

        // The sole remote dispatcher is installed only after all generated-operation
        // receivers are registered. This keeps startup from admitting a request into
        // a partially composed Poseidon runtime.
        let remote_handler = remote_operation_installer.map(|installer| installer.install(bus.input_sender()));

        let iroh = substrate.start(
            remote_handler,
            auth_construction.first_contact_handler.clone(),
            auth_construction.pairing_owner.clone(),
        );
        let bus = BusHandle::new(bus, transport_bindings, bus_publisher, root_jwt, peer_connectivity).await?;
        Ok(Self {
            domains: installed_domains,
            services,
            bus,
            auth_admission_registry: registry,
            auth_task,
            iroh,
            pairing_owner: auth_construction.pairing_owner,
            auth_service,
            shutdown_started: AtomicBool::new(false),
        })
    }

    /// Calls one generated public operation on a confirmed remote machine.
    pub async fn call_remote_operation(
        &self,
        target: MachineIssuerId,
        qualified_operation: String,
        input: serde_json::Value,
    ) -> Result<serde_json::Value, RemoteOperationError> {
        call_remote_operation_with(
            &self.iroh.remote_endpoint().await?,
            &self.pairing_owner,
            &self.auth_service,
            target,
            qualified_operation,
            input,
        )
        .await
    }

    /// Returns the shared registry used to admit locally and remotely issued JWTs.
    pub fn auth_admission_registry(&self) -> AuthAdmissionRegistry {
        self.auth_admission_registry.clone()
    }

    /// Returns a reader for one compile-time-selected service slot.
    pub fn service_reader<Service>(&self) -> ServiceReader<Service>
    where
        Service: ?Sized + Send + Sync + 'static,
    {
        self.services.declared_reader()
    }

    /// Subscribes to root broadcasts.
    pub fn subscribe_broadcasts(&self) -> broadcast::Receiver<RootBroadcast> {
        self.bus.subscribe_broadcasts()
    }

    /// Returns a clone of the opaque request ingress sender.
    pub fn request_sender(&self) -> mpsc::Sender<OpaqueRequestEnvelope> {
        self.bus.input_sender()
    }

    /// Returns the authenticated normal RPC context, or an unavailable context.
    pub fn rpc_context(&self) -> BusRpcContext {
        self.bus.rpc_context()
    }

    /// Starts every installed domain concurrently, like `Promise.all` over the
    /// descriptor callbacks.
    pub async fn start(&self) -> Result<(), ConfigError> {
        if let Some(config) = self
            .services
            .declared_reader::<dyn ConfigRegistrationSudoService>()
            .get()
        {
            config.seal_registration(SealRegistrationInput {}).await?;
        }
        let mut starts = JoinSet::new();
        for domain in &self.domains {
            starts.spawn(domain.start(self.bus.rpc_context()));
        }

        while starts.join_next().await.is_some() {}
        Ok(())
    }

    /// Stops and drains Sluice network ingress, then stops every installed domain through
    /// live bus ingress before shutting down the native Iroh handlers and bus. Domain
    /// callbacks contain and report their own failures.
    pub async fn shutdown(&self) -> Result<(), BusControlError> {
        if self.shutdown_started.swap(true, Ordering::AcqRel) {
            return Ok(());
        }

        let lifecycle_context = self.bus.rpc_context();
        let _ = tokio::time::timeout(Duration::from_secs(30), async {
            for domain in self
                .domains
                .iter()
                .filter(|domain| domain.name() == FlowDomain::RUNTIME_DOMAIN_NAME)
            {
                domain.stop(lifecycle_context.clone()).await;
            }
            let mut stops = JoinSet::new();
            for domain in self
                .domains
                .iter()
                .filter(|domain| domain.name() != FlowDomain::RUNTIME_DOMAIN_NAME)
            {
                stops.spawn(domain.stop(lifecycle_context.clone()));
            }
            while stops.join_next().await.is_some() {}
        })
        .await;

        let iroh_result = self.iroh.shutdown_router().await;
        self.iroh.close_endpoint().await;
        let bus_result = self.bus.shutdown().await;
        match (iroh_result, bus_result) {
            (Err(error), Ok(())) => {
                self.auth_task.abort();
                Err(BusControlError::Serve {
                    protocol: "iroh",
                    source: Box::new(error),
                })
            }
            (Ok(()), Ok(())) => {
                self.auth_task.abort();
                Ok(())
            }
            (_, Err(error)) => {
                self.shutdown_started.store(false, Ordering::Release);
                Err(error)
            }
        }
    }
}

/// Runtime implementation of the flow mobility service.
struct RuntimeFlowMobilityService {
    /// The flow sync services.
    services: FlowSyncServices,

    /// The auth service.
    auth_service: Arc<dyn AuthSudoService>,

    /// The source issuer.
    source_issuer: MachineIssuerId,

    /// The pairing owner.
    pairing_owner: PairingOwner,
}

impl FlowMobilityService for RuntimeFlowMobilityService {
    fn import_snapshot(
        &self,
        destination: FlowMobilityDestination,
        snapshot: FlowMobilitySnapshot,
    ) -> Pin<Box<dyn Future<Output = Result<FlowMobilityCommitAcknowledgement, FlowError>> + Send + '_>> {
        Box::pin(async move {
            let input = serde_json::json!({ "snapshot": snapshot, "sourcePeerKey": self.source_issuer });

            let output = self
                .call(destination.peer_key, "flow.importMobilitySnapshot", input)
                .await?;

            #[derive(serde::Deserialize)]
            struct CommitOutput {
                acknowledgement: FlowMobilityCommitAcknowledgement,
            }

            serde_json::from_value::<CommitOutput>(output)
                .map(|output| output.acknowledgement)
                .map_err(|error| FlowError::MobilityPeer {
                    message: error.to_string(),
                })
        })
    }

    fn promote_replica(
        &self,
        destination: FlowMobilityDestination,
        acknowledgement: FlowYieldAcknowledgement,
    ) -> Pin<Box<dyn Future<Output = Result<FlowActivationAcknowledgement, FlowError>> + Send + '_>> {
        Box::pin(async move {
            let input = serde_json::json!({ "flowId": acknowledgement.flow_id, "acknowledgement": acknowledgement });

            let output = self
                .call(destination.peer_key, "flow.promoteFlowReplica", input)
                .await?;

            #[derive(serde::Deserialize)]
            struct PromotionOutput {
                acknowledgement: FlowActivationAcknowledgement,
            }

            serde_json::from_value::<PromotionOutput>(output)
                .map(|output| output.acknowledgement)
                .map_err(|error| FlowError::MobilityPeer {
                    message: error.to_string(),
                })
        })
    }
}

impl RuntimeFlowMobilityService {
    async fn call(
        &self,
        target: MachineIssuerId,
        qualified_operation: &str,
        input: serde_json::Value,
    ) -> Result<serde_json::Value, FlowError> {
        let endpoint = self.services.native.read().await.endpoint.clone();
        if !self.services.connectivity.is_enabled() {
            return Err(WorkspaceError::ProviderUnavailable.into());
        }
        call_remote_operation_with(
            &endpoint,
            &self.pairing_owner,
            &self.auth_service,
            target,
            qualified_operation.to_owned(),
            input,
        )
        .await
        .map_err(|error| FlowError::MobilityPeer {
            message: error.to_string(),
        })
    }
}

async fn call_remote_operation_with(
    endpoint: &Endpoint,
    pairing_owner: &PairingOwner,
    auth_service: &Arc<dyn AuthSudoService>,
    target: MachineIssuerId,
    qualified_operation: String,
    input: serde_json::Value,
) -> Result<serde_json::Value, RemoteOperationError> {
    let (peer_endpoint, audience) = PairingCoordinator::refresh_audience(pairing_owner, &target)
        .await
        .map_err(|error| RemoteOperationError::Auth(Box::new(error)))?;

    let output = auth_service
        .issue_peer_jwt(IssuePeerJwtInput {
            target,
            audience,
            sub: "remote-operation".to_owned(),
            cap: vec![AuthCapability::AllBus],
        })
        .await
        .map_err(|error| RemoteOperationError::Auth(Box::new(error)))?;

    let request = RemoteOperationRequest {
        qualified_operation,
        input,
        jwt: output.token,
    };

    match call::<_, RemoteOperationReply<serde_json::Value>>(endpoint, peer_endpoint, &request).await? {
        RemoteOperationReply::Success(output) => Ok(output),
        RemoteOperationReply::DomainError(error) => Err(RemoteOperationError::Domain(error)),
        RemoteOperationReply::Rejected(error) => Err(RemoteOperationError::Rejected(error)),
    }
}

/// Declares one installed domain publication set.
///
/// The declaration emits lifecycle descriptors, one global RSPC router,
/// normal operation descriptors, and separate per-domain MCP publications
/// from the same ordered entries. Each marker must implement
/// [`DomainProviderMetadata`], which is generated by its `domain!` registry.
/// Provider metadata and duplicate-provider mappings are checked at compile
/// time. Each entry also declares the concrete broadcast type and root enum
/// variant used for its broadcast projection.
#[macro_export]
macro_rules! runtime_domains {
    (
        pub $name:ident {
            context: $context:ty,
            root_error: $root_error:ty,
            root_broadcast: $root_broadcast:ty,
            entries: [
                $(
                    $domain:ty => $rpc_router:path,
                    normal: $normal_operations:expr, mcp: $mcp_operations:expr,
                    $server_name:literal, $route_slug:literal,
                    broadcast: $broadcast:ty => $root_variant:ident
                ),* $(,)?
            ] $(,)?
        }
    ) => {
        trait __RuntimeDomainsUniqueProviderSet {}
        $(
            impl __RuntimeDomainsUniqueProviderSet
                for (
                    <$domain as $crate::DomainProviderMetadata>::ProviderSet,
                    $domain,
                )
            {}
        )*
        $(
            const _: fn() = || {
                fn assert_provider_metadata<T: $crate::DomainProviderMetadata>() {}
                assert_provider_metadata::<$domain>();
            };
        )*
        $(
            impl ::std::convert::From<$broadcast> for $root_broadcast {
                fn from(value: $broadcast) -> Self {
                    Self::$root_variant(value)
                }
            }
        )*

        pub struct $name;

        impl $name {
            pub fn lifecycle() -> ::std::vec::Vec<$crate::DomainDescriptor<$crate::bus::EventBus<$root_broadcast>>>
            where
                $(
                    $domain: $crate::runtime::DomainDescriptorFactory<$crate::bus::EventBus<$root_broadcast>>,
                )*
            {
                vec![
                    $(
                        $crate::DomainDescriptor::for_domain::<$domain>(stringify!($domain)),
                    )*
                ]
            }

            pub fn rpc_router() -> ::rspc::Router<$context> {
                ::rspc::Router::<$context>::new()
                    $(.nest($route_slug, $rpc_router()))*
            }

            pub fn normal_operation_descriptors() -> ::std::vec::Vec<
                &'static [$crate::bus::RequestOperationDescriptor<$context, $root_error>],
            > {
                vec![
                    $($normal_operations,)*
                ]
            }

            pub fn mcp_publications() -> ::std::vec::Vec<$crate::DomainPublication<$context, $root_error>> {
                vec![
                    $(
                        $crate::DomainPublication {
                            server_name: $server_name,
                            route_slug: $route_slug,
                            operations: $mcp_operations,
                        },
                    )*
                ]
            }
        }
    };
}

/// Error returned by a generated in-process bus client.
#[derive(Debug)]
pub enum GeneratedCallError<DomainError> {
    /// The request input channel is closed.
    InputClosed,
    /// The request handler dropped its reply channel.
    ReplyDropped,
    /// The domain handler returned its typed error.
    DomainError(DomainError),
    /// Authentication rejected the request before domain routing.
    Authentication(AvesAuthError),
    /// The reply did not contain the response variant declared by the operation.
    UnexpectedResponse { expected: String, actual: String },
}

impl<DomainError> fmt::Display for GeneratedCallError<DomainError>
where
    DomainError: fmt::Display,
{
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InputClosed => formatter.write_str("bus input is closed"),
            Self::ReplyDropped => formatter.write_str("bus reply was dropped"),
            Self::DomainError(error) => error.fmt(formatter),
            Self::Authentication(error) => error.fmt(formatter),
            Self::UnexpectedResponse { expected, actual } => {
                write!(formatter, "expected {expected}, got {actual}")
            }
        }
    }
}

impl<DomainError> std::error::Error for GeneratedCallError<DomainError>
where
    DomainError: std::error::Error + 'static,
{
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::DomainError(error) => Some(error),
            Self::Authentication(error) => Some(error),
            Self::InputClosed | Self::ReplyDropped | Self::UnexpectedResponse { .. } => None,
        }
    }
}

/// Error produced when a generated response cannot be projected to its variant.
#[derive(Debug, thiserror::Error)]
#[error("expected {expected}, got {actual}")]
pub struct ResponseProjectionError {
    /// The response variant requested by the operation.
    pub expected: String,
    /// Debug representation of the actual response.
    pub actual: String,
}

impl<DomainError> From<ResponseProjectionError> for GeneratedCallError<DomainError> {
    fn from(error: ResponseProjectionError) -> Self {
        Self::UnexpectedResponse {
            expected: error.expected,
            actual: error.actual,
        }
    }
}

