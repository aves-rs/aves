    #[tokio::test]
    #[cfg(feature = "keyring")]
    async fn runtime_shutdown_stops_domains_before_bus_and_is_idempotent() {
        SHUTDOWN_TEST_STOP_COUNT.store(0, Ordering::SeqCst);
        SHUTDOWN_TEST_DELIVERED.store(false, Ordering::SeqCst);
        let runtime = Runtime::<TestRootBroadcast>::new(
            runtime_test_options(),
            vec![
                DomainDescriptor::from_callbacks(
                    "ShutdownRegistration",
                    DomainCallbacks {
                        new: shutdown_test_construct,
                        start: |_| Box::pin(async {}),
                        stop: shutdown_test_stop,
                    },
                ),
                DomainDescriptor::from_callbacks(
                    "ShutdownSecond",
                    DomainCallbacks {
                        new: shutdown_test_noop_construct,
                        start: |_| Box::pin(async {}),
                        stop: shutdown_test_stop,
                    },
                ),
            ],
        )
        .await
        .expect("runtime bus finalization should succeed");

        runtime
            .shutdown()
            .await
            .expect("runtime shutdown should succeed");
        runtime
            .shutdown()
            .await
            .expect("second shutdown should be idempotent");
        assert_eq!(SHUTDOWN_TEST_STOP_COUNT.load(Ordering::SeqCst), 2);
        assert!(SHUTDOWN_TEST_DELIVERED.load(Ordering::SeqCst));
    }

